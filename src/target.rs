fn aggregate_directory_comparison(
    root_state: RootState,
    scan_unstable: bool,
    drifted: bool,
) -> Comparison {
    if root_state == RootState::Inaccessible || scan_unstable {
        Comparison::Unverifiable
    } else if drifted {
        Comparison::Drifted
    } else {
        Comparison::InSync
    }
}

fn inspect_root(path: &Path) -> RootState {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => RootState::Symlink,
        Ok(metadata) if metadata.is_dir() => match fs::read_dir(path) {
            Ok(_) => RootState::Directory,
            Err(_) => RootState::Inaccessible,
        },
        Ok(_) => RootState::Other,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => RootState::Absent,
        Err(_) => RootState::Inaccessible,
    }
}

fn has_symlink_ancestor(target_root: &Path, path: &Path) -> bool {
    let Ok(relative) = path.strip_prefix(target_root) else {
        return true;
    };
    let mut current = target_root.to_owned();
    for component in relative.components() {
        current.push(component.as_os_str());
        if current == path {
            break;
        }
        if fs::symlink_metadata(&current).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
            return true;
        }
    }
    false
}

fn read_children_stable(root: &Path) -> Result<Vec<PathBuf>, String> {
    fn names(root: &Path) -> Result<Vec<PathBuf>, std::io::Error> {
        let mut entries = fs::read_dir(root)?
            .map(|entry| entry.map(|entry| entry.path()))
            .collect::<Result<Vec<_>, _>>()?;
        entries.sort();
        Ok(entries)
    }
    read_children_stable_with(|| names(root))
}

fn read_children_stable_with(
    mut scan: impl FnMut() -> Result<Vec<PathBuf>, std::io::Error>,
) -> Result<Vec<PathBuf>, String> {
    let first = scan().map_err(|error| format!("cannot inspect directory: {error}"))?;
    let second = scan().map_err(|error| format!("cannot verify directory scan: {error}"))?;
    if first == second {
        Ok(first)
    } else {
        Err("skill folder changed while it was inspected".to_owned())
    }
}

fn inspect_control_file(
    target: &Target,
    relative: &Path,
    facts: Option<&PathFacts>,
    expected_content: &[u8],
) -> (ControlFileState, bool, bool, bool) {
    if target.git_repository().is_none() {
        return (ControlFileState::NotRequired, true, false, false);
    }
    let path = target.root().join(relative);
    let state = match fs::symlink_metadata(&path) {
        Ok(metadata) if !metadata.is_file() => ControlFileState::WrongKind,
        Ok(_) => match fs::read(&path) {
            Ok(bytes) if bytes == expected_content => ControlFileState::Canonical,
            Ok(bytes)
                if std::str::from_utf8(&bytes)
                    .is_ok_and(|content| !content.contains(CONTROL_FILE_EXCEPTIONS)) =>
            {
                ControlFileState::PrefixRequired
            }
            Ok(_) => ControlFileState::Modified,
            Err(_) => ControlFileState::Uninspectable,
        },
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => ControlFileState::Missing,
        Err(_) => ControlFileState::Uninspectable,
    };
    (
        state,
        facts.is_some_and(|facts| facts.tracked),
        facts.is_none_or(|facts| facts.tracked || facts.staged || facts.unmerged),
        facts.is_some_and(|facts| facts.ignored),
    )
}

fn control_file_content(
    entries: &BTreeSet<PathBuf>,
    parent: &Path,
    existing: Option<&[u8]>,
    repository_rules: Option<&BTreeSet<String>>,
) -> String {
    let mut content = CONTROL_FILE_CONTENT.to_owned();
    content.push_str(".gitignore\n");
    if parent == Path::new(".agents") {
        content.push_str("skillator.yaml\n");
    }
    for entry in entries {
        content.push_str(&escape_gitignore_literal(entry));
        content.push('\n');
    }
    content.push('\n');
    content.push_str(CONTROL_FILE_EXCEPTIONS);
    content.push('\n');
    let preserved = existing
        .and_then(|bytes| std::str::from_utf8(bytes).ok())
        .map(|existing| {
            existing
                .split_once(CONTROL_FILE_EXCEPTIONS)
                .map_or(existing, |(_, exceptions)| {
                    exceptions.strip_prefix('\n').unwrap_or(exceptions)
                })
        })
        .unwrap_or_default();
    content.push_str(preserved);
    if !preserved.is_empty() && !preserved.ends_with('\n') {
        content.push('\n');
    }
    for rule in repository_rules.into_iter().flatten() {
        if !preserved.lines().any(|line| line == rule) {
            content.push_str(rule);
            content.push('\n');
        }
    }
    content
}

fn escape_gitignore_literal(path: &Path) -> String {
    let value = path.to_string_lossy();
    let final_wildcard =
        value.ends_with("/*") || value == ".skillator-*" || value.ends_with("/.skillator-*");
    let mut escaped = String::with_capacity(value.len());
    for (index, character) in value.char_indices() {
        let is_allowed_wildcard =
            final_wildcard && character == '*' && index + character.len_utf8() == value.len();
        if (matches!(character, '\\' | '*' | '?' | '[' | ']') && !is_allowed_wildcard)
            || (index == 0 && matches!(character, '#' | '!'))
        {
            escaped.push('\\');
        }
        escaped.push(character);
    }
    escaped
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn changing_immediate_child_scan_is_unstable() {
        let mut scans = vec![vec![PathBuf::from("one")], vec![PathBuf::from("two")]].into_iter();
        let result = read_children_stable_with(|| Ok(scans.next().expect("two scans")));
        assert_eq!(
            result.unwrap_err(),
            "skill folder changed while it was inspected"
        );
    }

    #[test]
    fn stable_immediate_child_scan_returns_snapshot() {
        let expected = vec![PathBuf::from("one"), PathBuf::from("two")];
        let result = read_children_stable_with(|| Ok(expected.clone())).unwrap();
        assert_eq!(result, expected);
    }

    #[test]
    fn unstable_scan_makes_directory_unverifiable_even_without_other_drift() {
        assert_eq!(
            aggregate_directory_comparison(RootState::Directory, true, false),
            Comparison::Unverifiable
        );
    }

    #[test]
    fn control_file_escapes_gitignore_metacharacters() {
        assert_eq!(
            escape_gitignore_literal(Path::new("skills/foo*?[bar]")),
            r"skills/foo\*\?\[bar\]"
        );
        assert_eq!(escape_gitignore_literal(Path::new("#skills")), r"\#skills");
        assert_eq!(escape_gitignore_literal(Path::new("skills/*")), "skills/*");
        assert_eq!(
            escape_gitignore_literal(Path::new("é/skills/.skillator-*")),
            "é/skills/.skillator-*"
        );
    }

    #[test]
    fn generated_control_prefixes_unmarked_content_and_adds_repository_rules() {
        let entries = BTreeSet::from([PathBuf::from("skills/*")]);
        let rules = BTreeSet::from(["!skills/project-skill/".to_owned()]);

        let content = control_file_content(
            &entries,
            Path::new(".agents"),
            Some(b"# Existing rules\n*.local\n"),
            Some(&rules),
        );

        assert_eq!(
            content,
            "# Generated by Skillator\n.gitignore\nskillator.yaml\nskills/*\n\n# Exception list for repository tracking\n# Existing rules\n*.local\n!skills/project-skill/\n"
        );
    }
}
