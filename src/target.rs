#[derive(Debug, thiserror::Error)]
pub enum TargetError {
    #[error("Directory does not exist: {0}")]
    Missing(PathBuf),
    #[error("Path is not a directory: {0}")]
    NotDirectory(PathBuf),
    #[error("Directory is not in a Git worktree: {0}")]
    NotGit(PathBuf),
    #[error("Directory is a bare Git repository; use a working checkout: {0}")]
    Bare(PathBuf),
    #[error("Cannot inspect the directory: {0}")]
    Io(#[from] std::io::Error),
    #[error(transparent)]
    Git(#[from] GitError),
}

#[derive(Debug, Clone)]
pub struct Target {
    supplied_path: PathBuf,
    root: PathBuf,
    repository: Option<GitRepository>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TargetScope {
    Repository,
    User,
}

pub const CONTROL_FILE_CONTENT: &str = "# Generated by Skillator\n";
pub const CONTROL_FILE_EXCEPTIONS: &str = "# Exception list for repository tracking";
pub type RepositorySkillExceptions = BTreeMap<String, BTreeSet<String>>;

pub fn control_file_path(directory: &SkillDirectoryConfig) -> PathBuf {
    Path::new(directory.path().as_str())
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(".gitignore")
}

pub fn repository_tracking_rule(directory: &SkillDirectoryConfig, name: &str) -> Option<String> {
    let control = control_file_path(directory);
    let parent = control.parent().unwrap_or_else(|| Path::new("."));
    let skill_root = Path::new(directory.path().as_str())
        .strip_prefix(parent)
        .ok()?;
    Some(format!(
        "!{}/",
        escape_gitignore_literal(&skill_root.join(name))
    ))
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RootState {
    Absent,
    Directory,
    Inaccessible,
    Symlink,
    Other,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Comparison {
    InSync,
    Drifted,
    Unverifiable,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MaterializationState {
    Missing,
    CanonicalLink,
    NoncanonicalLink,
    BrokenLink,
    MisdirectedLink,
    EquivalentCopy,
    DivergedCopy,
    CopyIneligible,
    WrongKind,
    Uninspectable,
    ExpectedEntryCollision,
    UnknownExpectedEntry,
}

impl MaterializationState {
    pub fn description(&self) -> &'static str {
        match self {
            Self::Missing => "Skill link or copy is missing",
            Self::CanonicalLink | Self::EquivalentCopy => "Up to date",
            Self::NoncanonicalLink => "Link needs updating",
            Self::BrokenLink => "Link destination is missing",
            Self::MisdirectedLink => "Link points to a different skill",
            Self::DivergedCopy => "Local copy differs from the library",
            Self::CopyIneligible => "Skill contains files or links that cannot be copied safely",
            Self::WrongKind => "An existing file or folder is in the way",
            Self::Uninspectable => "Cannot read the skill files",
            Self::ExpectedEntryCollision => "Multiple skills use the same destination name",
            Self::UnknownExpectedEntry => "Cannot determine the skill's destination name",
        }
    }
}

impl Comparison {
    pub fn description(self) -> &'static str {
        match self {
            Self::InSync => "Up to date",
            Self::Drifted => "Changes still needed",
            Self::Unverifiable => "Cannot verify the files",
        }
    }
}

